"""compose.personas.yml, generated from the personas as text: byte for byte the services the setup tool has
always written, under a header that says where they come from (personas.json).

No YAML library: nexus renders it too and compares the bytes with the file (one edited by hand is out of
step), the tests look for exact lines in it, and compose expands the ${…} in it, not this code.

render(personas, managed=…, env_files=…, legacy=…): the whole file. managed: whether
personas/claude.managed.json exists (its mount is left out otherwise); env_files: a name → env file path map
for the staged check before a commit (personas/NAME.env otherwise); legacy: the comments as config-tools
wrote them, before it was `nexus --config`.

Pitfalls (each pinned where named):
- byte for byte, its comments too: the services as the bash wrote them
  (test_adapters.Render.test_as_the_goldens_have_it)
- a key's path goes into '…' as it is: persona.key_path_ok must keep refusing ' and $ (golden
  config/cli-bad-ssh)
- a persona that asks gets personas/claude.ask.json whether or not it is there: left out, it would bypass (and a
  start without it is refused) (test_adapters.Render.test_ask, golden nexus/perm-ask-file-missing)
"""
from agentctl.domain import context, flavour

HEADER = (
    "# compose.personas.yml — generated by nexus --config from personas.json; don't edit it. Re-run\n"
    "# nexus --config to add, change or remove personas: nexus won't create a container from a file that\n"
    "# isn't what personas.json gives.\n"
)

# The same, as config-tools wrote them before it was `nexus --config`: a file written then is still in step
# (render(…, legacy=True)), until the next writing run writes it as it is now.
LEGACY = (
    (HEADER, "# compose.personas.yml — generated by ./config-tools from personas.json; don't edit it. Re-run\n"
             "# config-tools to add, change or remove personas: nexus won't create a container from a file that\n"
             "# isn't what personas.json gives.\n"),
    ("written by nexus --config: personas/grok.toml", "written by config-tools: personas/grok.toml"),
)

MANAGED = (
    "      # The Claude Code settings that hold in every Claude persona, personas/claude.managed.json, as a\n"
    "      # managed drop-in: they win over its own settings (the defaults in personas/claude.json don't: nexus\n"
    "      # merges those into them). A single-file mount, so a change (a git pull too) needs a restart.\n"
    "      - { type: bind, source: ./personas/claude.managed.json, target: "
    "/etc/claude-code/managed-settings.d/15-personas.json, read_only: true, bind: { create_host_path: false } }\n"
)

CLAUDE_ASK = (
    "      # It asks before running tools: personas/claude.ask.json, a managed drop-in after 15-personas.json, so\n"
    "      # the permission mode it sets wins over the bypassPermissions there. A single-file mount, so a change\n"
    "      # needs a restart.\n"
    "      - { type: bind, source: ./personas/claude.ask.json, target: "
    "/etc/claude-code/managed-settings.d/16-ask.json, read_only: true, bind: { create_host_path: false } }\n"
)

CLAUDE_STATUSLINE = (
    "      # Claude Code statusline: the script's directory, so edits and pulls show up live, and its\n"
    "      # setting as a managed drop-in (beats a user statusLine). The drop-in is a single-file mount,\n"
    "      # so a change to statusline/claude/settings.json needs `nexus <persona> restart`.\n"
    "      - ./statusline/claude:/etc/claude-code/statusline:ro\n"
    "      - ./statusline/claude/settings.json:/etc/claude-code/managed-settings.d/20-statusline.json:ro\n"
)

GROK_STATUSLINE = (
    "      # grok's statusline: the script's directory, so edits and pulls show up live.\n"
    "      - ./statusline/grok:/etc/grok/statusline:ro\n"
)

GROK_CONFIG = (
    "      # grok's managed config, written by nexus --config: personas/grok.toml, then the statusline's\n"
    "      # [ui.status_line] with the statusline on. A key in the persona's ~/.grok/config.toml wins.\n"
    "      - { type: bind, source: ./personas/{name}.grok.toml, target: /etc/grok/managed_config.toml, "
    "read_only: true, bind: { create_host_path: false } }\n"
)

NO_SSH = (
    "      # No ssh: your ssh-agent isn't mounted (/dev/null takes the socket's place, SSH_AUTH_SOCK is\n"
    "      # empty), and its ssh setting makes git over ssh fail at once rather than ask for a password.\n"
    "      - ./ssh/none.conf:/etc/ssh/ssh_config.d/50-nexus-none.conf:ro\n"
    "      - { type: bind, source: /dev/null, target: /ssh-agent }\n"
)

OWN_KEY = (
    "      # Its own ssh key, read-only, and the ssh setting that makes ssh (and git over ssh) use it. Your\n"
    "      # ssh-agent isn't mounted: /dev/null takes the socket's place, and SSH_AUTH_SOCK is empty.\n"
    "      - type: bind\n"
    "        source: '{key}'\n"
    "        target: /run/nexus/ssh-key\n"
    "        read_only: true\n"
    "        bind: { create_host_path: false }\n"
    "      - ./ssh/key.conf:/etc/ssh/ssh_config.d/50-nexus-key.conf:ro\n"
    "      - { type: bind, source: /dev/null, target: /ssh-agent }\n"
)


def _service(p, env_file, managed):
    fl, cx = flavour.get(p.flavour), context.get(p.context)
    more = ', SSH_AUTH_SOCK: ""' if p.ssh else ""
    s = (
        "\n"
        "  \"%(n)s\":\n"
        "    extends: { file: compose.yml, service: %(base)s }\n"
        "    profiles: [\"%(n)s\", \"all\"]\n"
        "    image: ${REGISTRY:-local}/agent-%(f)s-%(c)s:%(tag)s\n"
        "    build: { target: %(f)s, args: { CONTEXT: %(c)s } }\n"
        "    container_name: agent-%(n)s\n"
        "    env_file: %(env)s\n"
        "    environment: { AGENT_PERSONA: \"%(n)s\", AGENT_COLOUR: %(col)s%(more)s }\n"
        "    labels: { agent.persona: \"%(n)s\", agent.flavour: %(f)s, agent.context: %(c)s }\n"
        "    volumes:\n"
        "      - %(n)s-home:/home/dev\n"
    ) % {"n": p.name, "base": cx.base_service, "f": p.flavour, "c": p.context, "tag": fl.image_tag,
         "env": env_file, "col": p.colour, "more": more}
    if p.flavour == "claude" and managed:
        s += MANAGED
    if p.flavour == "claude" and p.permissions == "ask":
        s += CLAUDE_ASK
    if p.flavour == "claude" and p.statusline:
        s += CLAUDE_STATUSLINE
    elif p.flavour == "grok":
        if p.statusline:
            s += GROK_STATUSLINE
        s += GROK_CONFIG.replace("{name}", p.name)
    if p.ssh == "none":
        s += NO_SSH
    elif p.ssh:
        k = p.ssh if p.ssh.startswith("/") else "./" + p.ssh
        s += OWN_KEY.replace("{key}", k)
    return s


def service(p, managed):
    """One persona's service, as render() writes it into the file."""
    return _service(p, "personas/%s.env" % p.name, managed)


def render(personas, managed, env_files=None, legacy=False):
    env_files = env_files or {}
    out = HEADER
    out += "\nservices:\n"
    for p in personas:
        out += _service(p, env_files.get(p.name, "personas/%s.env" % p.name), managed)
    out += "\nvolumes:\n"
    for p in personas:
        out += "  \"%s-home\":\n" % p.name
    if legacy:
        for now, then in LEGACY:
            out = out.replace(now, then)
    return out
