"""Telemetry: OpenTelemetry from the personas to one collector, when nexus --config is given one. No I/O here.

The shared settings, in .env: TELEMETRY_ENDPOINT, the collector's OTLP/HTTP base URL (empty: off);
TELEMETRY_TOKEN, its bearer token (empty: none is sent); TELEMETRY_CA, the CA its certificate is signed by, as
nexus --config copied it into the checkout (personas/telemetry-ca.pem; empty: a publicly trusted certificate). A
persona sends only when it says so (personas.json "telemetry": true), and only while an endpoint is set.

What a persona that sends gets, generated by nexus --config:
- claude: personas/NAME.telemetry.json, a managed-settings drop-in whose env turns Claude Code's exporters on
  (metrics, events, traces; http/protobuf), with the token as a header, host.name and persona as resource
  attributes (Claude Code copies them onto every datapoint, event and span), and the CA as NODE_EXTRA_CA_CERTS.
  A drop-in, not the container's environment: it beats the process env, and no other program in the persona
  sees an OTEL_*ENDPOINT (docker compose sends its own traces when it sees one). Claude Code takes the CA from
  NODE_EXTRA_CA_CERTS only, and a drop-in's value replaces the one compose gives a ddev persona (mkcert's CA),
  for all of Claude's TLS: a ddev persona gets a bundle of both (bundle(), written by nexus when it starts it).
- grok: a [telemetry] table after its managed config (grok sends metrics and events, no traces), and
  personas/NAME.telemetry.env, a second env file holding the token header: grok has no setting for headers. It
  holds them as OTEL_EXPORTER_OTLP_METRICS_HEADERS and _LOGS_HEADERS, which grok reads, rather than the generic
  OTEL_EXPORTER_OTLP_HEADERS: every process in the persona sees its environment, and docker compose and a
  project's tracing (traces only) then don't send the token anywhere; a project's own metrics or logs exporter
  still would. grok ignores OTEL_RESOURCE_ATTRIBUTES, so the host and persona go as X-Nexus-Host and
  X-Nexus-Persona headers, which a collector can turn into attributes.
- A claude persona that stops sending (or turns grok) gets NEUTRAL in its drop-in, not none: a running container
  still mounts the file, and Docker couldn't start it again (a reboot) without it; nexus removes the file when it
  next creates the container without the mount.
Prompts and responses aren't sent: neither CLI sends them unless told to (OTEL_LOG_USER_PROMPTS), and nexus doesn't.

Pitfalls (each pinned where named):
- the header with a literal space after Bearer: Claude Code doesn't decode %20 (test_domain.Telemetry.test_claude_dropin)
- an endpoint without a scheme breaks grok's exporter, and http/json turns it off: https:// or http:// only, and
  only http/protobuf (test_domain.Telemetry.test_rules)
- a token with a comma or a space would split the header list (test_domain.Telemetry.test_rules)
- the bundle: the CA first, then mkcert's, each ending in a newline (test_domain.Telemetry.test_bundle)
- grok's token in its metrics and logs headers only, never OTEL_EXPORTER_OTLP_HEADERS (test_domain.Telemetry.test_grok)
- a host name with anything but letters, digits and - is left out: it would split the attribute or header list
  (test_domain.Telemetry.test_rules)
"""
import json
import re

CA_FILE = "personas/telemetry-ca.pem"            # the collector's CA, as nexus --config copied it
DDEV_BUNDLE = "personas/telemetry-ca.ddev.pem"   # that CA and mkcert's, for a ddev claude persona
CA_TARGET = "/etc/nexus/telemetry-ca.pem"        # where a persona sees either
DROPIN_TARGET = "/etc/claude-code/managed-settings.d/50-telemetry.json"
PROTOCOL = "http/protobuf"
NEUTRAL = "{}\n"                                   # the drop-in of a claude persona that no longer sends
GROK_HEADERS = ("OTEL_EXPORTER_OTLP_METRICS_HEADERS", "OTEL_EXPORTER_OTLP_LOGS_HEADERS")

ENDPOINT_RULE = "https://host[:port] (or http://), the collector's OTLP/HTTP address, e.g. https://collector.lan:4318"
TOKEN_RULE = "letters, digits and . _ ~ + / = - only"

_ENDPOINT = re.compile(r"https?://[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?(:[0-9]{1,5})?(/[A-Za-z0-9._~/-]*)?")
_TOKEN = re.compile(r"[A-Za-z0-9._~+/=-]{1,4096}")


def dropin_file(name):
    return "personas/%s.telemetry.json" % name


def env_file(name):
    return "personas/%s.telemetry.env" % name


def norm_endpoint(url):
    """The endpoint as saved: without a trailing / (the CLIs add /v1/metrics and the like)."""
    while url.endswith("/") and url.count("/") > 2:
        url = url[:-1]
    return url


def valid_endpoint(url):
    return _ENDPOINT.fullmatch(url) is not None


def valid_token(token):
    return _TOKEN.fullmatch(token) is not None


def safe_host(host):
    """HOST as the files take it, or "" when it has anything but letters, digits and -."""
    return host if re.fullmatch(r"[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?", host) else ""


def ca_source(p, ca):
    """The file a persona's CA mount comes from, if the collector has a CA of its own (CA): the bundle for a ddev
    claude persona, the CA for any other."""
    if not ca:
        return ""
    return DDEV_BUNDLE if (p.flavour, p.context) == ("claude", "ddev") else CA_FILE


def claude_dropin(name, host, endpoint, token, ca):
    """personas/NAME.telemetry.json: Claude Code's exporters, as a managed drop-in's env."""
    env = {
        "CLAUDE_CODE_ENABLE_TELEMETRY": "1",
        "OTEL_METRICS_EXPORTER": "otlp",
        "OTEL_LOGS_EXPORTER": "otlp",
        "OTEL_TRACES_EXPORTER": "otlp",
        "CLAUDE_CODE_ENHANCED_TELEMETRY_BETA": "1",
        "OTEL_EXPORTER_OTLP_PROTOCOL": PROTOCOL,
        "OTEL_EXPORTER_OTLP_ENDPOINT": endpoint,
    }
    if token:
        env["OTEL_EXPORTER_OTLP_HEADERS"] = "Authorization=Bearer " + token
    env["OTEL_RESOURCE_ATTRIBUTES"] = ",".join(("host.name=" + host if host else "", "persona=" + name)).lstrip(",")
    if ca:
        env["NODE_EXTRA_CA_CERTS"] = CA_TARGET
    return json.dumps({"env": env}, indent=2) + "\n"


def grok_table(endpoint, ca):
    """The [telemetry] table after a grok persona's managed config."""
    lines = ["", "# Telemetry (nexus --config, telemetry in its menu): metrics and events to the collector in .env.",
             "# The token comes from the environment (personas/<name>.telemetry.env): grok has no setting for it.",
             "[telemetry]",
             "otel_enabled = true",
             'otel_metrics_exporter = "otlp"',
             'otel_logs_exporter = "otlp"',
             "otel_protocol = %s" % json.dumps(PROTOCOL),
             "otel_endpoint = %s" % json.dumps(endpoint)]
    if ca:
        lines.append("otel_certificate = %s" % json.dumps(CA_TARGET))
    return "\n".join(lines) + "\n"


def grok_env(name, host, token):
    """personas/NAME.telemetry.env: the headers grok sends with every export of metrics and of events, in '…'
    (compose takes those as they are; a token, a name and a host have no ' in them)."""
    headers = (["Authorization=Bearer " + token] if token else []) + ["X-Nexus-Persona=" + name]
    if host:
        headers.append("X-Nexus-Host=" + host)
    return ("# personas/%s.telemetry.env: written by nexus --config from TELEMETRY_TOKEN in .env, for grok's telemetry\n"
            "# (it takes the token from the environment only; as the metrics and logs headers, which nothing but an\n"
            "# exporter of those reads). Don't edit it: re-run nexus --config.\n" % name
            + "".join("%s='%s'\n" % (v, ",".join(headers)) for v in GROK_HEADERS))


def bundle(ca, mkcert):
    """The ddev bundle's bytes: the collector's CA, then mkcert's (if there is one), each ending in a newline."""
    out = b""
    for part in (ca, mkcert):
        if part:
            out += part if part.endswith(b"\n") else part + b"\n"
    return out
